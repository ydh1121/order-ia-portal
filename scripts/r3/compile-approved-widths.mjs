// Precompute additional QA viewport identities so a cold Pages isolate can serve the catalog immediately.
import {createHash} from 'node:crypto';
import {writeFileSync} from 'node:fs';
import {catalog} from '../../src/server/r3-ui/catalog.gen.mjs';
import {additionalWidths} from '../../src/server/r3-ui/approved-width-list.mjs';

const hash = value=>createHash('sha256').update(value).digest('hex');
const entries = new Map();
for(const row of catalog){
  for(const width of additionalWidths){
    const source=row.hashes[width<768?390:1440];
    if(!entries.has(source))entries.set(source,{});
    entries.get(source)[width]=hash('MSG0585-R3|viewport|'+width+'|'+source);
  }
}
const lines=[...entries].map(([base,widths])=>JSON.stringify(base)+':'+JSON.stringify(widths));
const output=new URL('../../src/server/r3-ui/approved-widths.gen.mjs',import.meta.url);
writeFileSync(output,'// Generated by scripts/r3/compile-approved-widths.mjs. Lookup requires an exact released source hash.\nexport const widthIndex={\n'+lines.join(',\n')+'\n};\n');
