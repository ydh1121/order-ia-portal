// Run after changing current authored frames. Keep the merged R3 reviewer’s actual
// artifact bytes/width hashes available without modifying the R2 "previous" catalog.
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {gzipSync} from 'node:zlib';
import {writeFileSync} from 'node:fs';
import {catalog, cssHash, frames} from '../../src/server/r3-ui/catalog.gen.mjs';
import {frameCode} from '../../src/server/r3-ui/runtime.gen.mjs';
const root=new URL('../../',import.meta.url);
const ref=process.argv[2] || 'c88d938';
function at(path){
  const content=execFileSync('git',['show',ref+':src/server/r3-ui/'+path],{cwd:root,maxBuffer:16_000_000});
  return import('data:text/javascript;base64,'+content.toString('base64'));
}
const old=await at('catalog.gen.mjs'), runtime=await at('runtime.gen.mjs');
if(old.cssHash!==cssHash || runtime.frameCode!==frameCode)throw Error('Archive the shared CSS and frame engine before changing their release identity');
const defaultFamily={login:'account',signup:'account',otp:'account',password:'account',terms:'account',business:'business',proof:'business',signature:'business',onboarding:'member','quote-wait':'member'};
const byId=new Map(catalog.map(r=>[r.id,r]));
const rows={},documents={},scripts={};
for(const entry of old.catalog){
  const current=byId.get(entry.id);
  if(!current)throw Error('Removed existing review id '+entry.id);
  if(Object.entries(entry.hashes).every(([w,h])=>current.hashes[w]===h))continue;
  const code=runtime.runtimes[entry.runtimeFamily || defaultFamily[entry.screen]];
  let script=null;
  if(code){
    script=createHash('sha256').update(code).digest('hex');
    scripts[script]??=gzipSync(code).toString('base64');
  }
  const body=entry.current;
  if(!frames[body])documents[body]=old.frames[body];
  rows[entry.id]={hashes:entry.hashes,body,script};
}
const output=new URL('src/server/r3-ui/reviewed-r3.gen.mjs',root);
writeFileSync(output,'// Previous R3 review identities and compressed content; generated by archive-reviewed-release.mjs.\n'+
  Object.entries({archivedRows:rows,archivedBodies:documents,archivedScripts:scripts}).map(([key,v])=>'export const '+key+'='+JSON.stringify(v)+';').join('\n')+'\n');
console.log('Archived R3 frame revisions:',Object.keys(rows).length);
