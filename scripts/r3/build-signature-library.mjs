import {readFile,writeFile} from 'node:fs/promises';
import {browserFunction} from '../../src/server/browser-source.mjs';
import {installProductWorkflowMotion,productWorkflowMotionCss} from '../../src/server/product-workflow-motion.mjs';
import {createDocumentSignaturePad,researchWorkflowPolishCss} from '../../src/server/research-app/workflow-polish.mjs';

const signatureLibraryCss=productWorkflowMotionCss+researchWorkflowPolishCss+
  '.signature-page .research-evidence-settings[data-library-signature-slot]{max-width:342px;padding:0;margin:12px 0}.qa-library-chrome .qa-signature-demo{grid-column:1/-1}.qa-signature-demo>.qa-asset-uses{max-width:520px}';

function installLibraryPad(win,createPad,installWorkflow){
  // The board and the common index mount their existing review modules normally.
  // Both host the exact field used when a customer signs their documents.
  const slot=win.document.querySelector('[data-library-signature-slot]');
  if(!slot||slot.firstElementChild)return;
  const workflow=win.ORDER_WORKFLOW_MOTION||installWorkflow(win);
  const pad=createPad(win,workflow.signaturePad.bind(workflow));
  slot.append(pad.element);
  const productLab=win.frameElement?.id==='product-frame'||new URL(win.location.href).searchParams.get('view')==='product-r3';
  if(productLab){
    // A product case does not manufacture submitted or missing review states.
    // Open the original state in the signed review shell at the selected width.
    for(const button of win.document.querySelectorAll('.qa-signature-demo [data-source-usage]')){
      const link=win.document.createElement('a'),id=button.dataset.sourceUsage;
      link.className=button.className;link.dataset.sourceUsage=id;
      link.target='_top';link.href='/ia?'+new URLSearchParams({view:'qa-lab',screen:id,width:String(win.innerWidth),version:'current'});
      link.append(...button.childNodes);button.replaceWith(link);
    }
  }
  win.addEventListener('pagehide',()=>pad.destroy(),{once:true});
}
function signatureLibraryMount(){
  return '('+browserFunction(installLibraryPad)+')(window,'+browserFunction(createDocumentSignaturePad)+','+browserFunction(installProductWorkflowMotion)+');';
}

const file=new URL('../../src/server/signature-library-runtime.gen.mjs',import.meta.url);
const source='// Generated by scripts/r3/build-signature-library.mjs from the product signature implementation.\nexport const signatureLibraryCss='+JSON.stringify(signatureLibraryCss)+';\nexport const signatureLibraryRuntime='+JSON.stringify(signatureLibraryMount())+';\n';
if(process.argv.includes('--check')){if(await readFile(file,'utf8')!==source)throw Error('Stale signature library runtime');}
else await writeFile(file,source);
