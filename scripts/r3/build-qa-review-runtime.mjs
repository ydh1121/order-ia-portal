// Freeze canonical browser functions before bundling. The artifact's reviewed
// source hash must be identical locally and inside the deployed Pages Worker.
import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import {getPriceWorkspaceQaRuntimeSource} from '../../src/server/r3-price-workspace-qa.mjs';
import {bootQaHost} from '../../src/server/r3-ui/host.mjs';
import {browserFunction} from '../../src/server/browser-source.mjs';
import {installProductAdapter} from '../../src/server/product-app-adapter.mjs';
import {installQaFixtureAdapter} from '../../src/server/r3-ui/qa-fixture-adapter.mjs';
import {installQaReviewRuntime} from '../../src/server/r3-ui/qa-review-runtime.mjs';
import {sharedCoreScript,commonMotionScript} from '../../src/server/product-ui/assets.gen.mjs';
import {getProductUiBootstrap} from '../../src/server/product-ui/bootstrap.gen.mjs';
import {getProductAuthSheetBootstrap} from '../../src/server/product-auth-sheet.mjs';

if(!process.argv.includes('--review-phase')){
  const hostFile=new URL('../../src/server/r3-ui/review-engine.gen.mjs',import.meta.url),oldHost=await readFile(hostFile,'utf8');
  const nextHost=oldHost.replace(/^export const hostCode=.*;$/m,()=> 'export const hostCode='+JSON.stringify(browserFunction(bootQaHost))+';');
  if(process.argv.includes('--check')){if(nextHost!==oldHost)throw Error('QA host runtime needs regeneration');}
  else if(nextHost!==oldHost)await writeFile(hostFile,nextHost);
  const priceSource=await getPriceWorkspaceQaRuntimeSource();
  const priceOutput='// Generated from the canonical price workspace and QA fixture transport.\nexport const priceWorkspaceQaRuntimeSource='+JSON.stringify(priceSource)+';\n';
  const priceFile=new URL('../../src/server/r3-price-workspace-qa-runtime.gen.mjs',import.meta.url);
  if(process.argv.includes('--check')){if(await readFile(priceFile,'utf8')!==priceOutput)throw Error('QA price runtime needs regeneration');}
  else await writeFile(priceFile,priceOutput);
  const output=execFileSync(process.execPath,[fileURLToPath(import.meta.url),'--review-phase',...(process.argv.includes('--check')?['--check']:[])],{encoding:'utf8'});
  process.stdout.write(output);
  process.exit(0);
}
const {getProductPanelBootstrap}=await import('../../src/server/product-account-panels.mjs');
const panel=await getProductPanelBootstrap();
const authSheet=await getProductAuthSheetBootstrap();
const productUi=getProductUiBootstrap();
const script=sharedCoreScript+'\nif(!window.OrderMagneticAction){'+commonMotionScript+'}\n'+productUi.script+'\n'+panel.script+'\n'+authSheet.script+
  '\nwindow.ORDER_QA_REVIEW_RUNTIME=function(session){return ('+browserFunction(installQaReviewRuntime)+')(session,'+browserFunction(installQaFixtureAdapter)+','+browserFunction(installProductAdapter)+');};';
const sources=['src/server/r3-ui/qa-fixture-adapter.mjs','src/server/product-app-adapter.mjs','src/server/product-account-panels.mjs','src/server/product-auth-sheet.mjs','scripts/r3/authored/account.js','scripts/r3/authored/account.css','src/server/r3-ui/qa-mvp-runtime.mjs','src/server/product-ui/modules.mjs','src/server/product-ui/documents.mjs','src/server/product-ui/bootstrap.gen.mjs','src/server/r3-common-motion.mjs','src/server/r3-async-motion.mjs','src/server/product-admin-motion.mjs','src/server/product-workflow-motion.mjs','src/server/r3-evidence-client.mjs','src/server/order-engine/browser/brand-account-menu.mjs','src/server/order-engine/browser/code1-jelly.mjs'];
const css=productUi.css+panel.css+authSheet.css;
const digest=createHash('sha256').update(JSON.stringify([script,css,sources])).digest('hex');
const values={qaReviewRuntimeScript:script,qaReviewRuntimeCss:css,qaReviewRuntimeDigest:digest,qaReviewRuntimeSources:sources};
const output='// Generated by scripts/r3/build-qa-review-runtime.mjs. Current QA only; historical sources are unchanged.\n'+Object.entries(values).map(([key,value])=>'export const '+key+'='+JSON.stringify(value)+';').join('\n')+'\n';
const file=new URL('../../src/server/r3-ui/qa-review-runtime.gen.mjs',import.meta.url);
if(process.argv.includes('--check')){if(await readFile(file,'utf8')!==output)throw Error('QA review runtime needs regeneration');}
else await writeFile(file,output);
console.log(JSON.stringify({digest,bytes:Buffer.byteLength(output)}));
