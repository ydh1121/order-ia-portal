import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {getProductUiBootstrap} from '../../src/server/product-ui/bootstrap.mjs';

// Freeze serialization before bundling. Worker function-name instrumentation
// must not alter artifact identities or the product/review bootstrap contract.
const {script,css}=getProductUiBootstrap();
const digest=createHash('sha256').update(JSON.stringify([script,css])).digest('hex');
const values={productUiScript:script,productUiCss:css,productUiDigest:digest};
const output='// Canonical product bootstrap. Generated by build-product-ui-bootstrap.mjs.\n'+Object.entries(values).map(([key,value])=>'export const '+key+'='+JSON.stringify(value)+';').join('\n')+'\nexport function getProductUiBootstrap(){return {script:productUiScript,css:productUiCss};}\n';
const target=new URL('../../src/server/product-ui/bootstrap.gen.mjs',import.meta.url);
if(process.argv.includes('--check')){if(await readFile(target,'utf8')!==output)throw Error('Product UI bootstrap needs regeneration');}
else await writeFile(target,output);
console.log(JSON.stringify({digest,bytes:Buffer.byteLength(output)}));
