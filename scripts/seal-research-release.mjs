import {readFile,writeFile,mkdir,rename,unlink} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {gzipSync,gunzipSync} from 'node:zlib';
import {fileURLToPath,pathToFileURL} from 'node:url';
import {dirname,join,resolve,posix} from 'node:path';
import {execFileSync} from 'node:child_process';
import {RESEARCH_RELEASE_FORMAT,RESEARCH_RELEASE_NONCE,RESEARCH_RELEASE_FULL_ROWS,RESEARCH_RELEASE_ROW_IDENTITIES,researchReleaseRowIdentities,createResearchReleaseStore} from '../src/server/research-app/release-store.mjs';

const repository=fileURLToPath(new URL('../',import.meta.url));
const hash=value=>createHash('sha256').update(value).digest('hex');
const gzip=value=>gzipSync(value,{level:9,mtime:0});
const safePath=value=>typeof value==='string'&&/^[\w./-]+$/.test(value)&&!value.startsWith('/')&&!value.includes('..')&&!value.includes('//');
const missing=error=>error?.code==='ENOENT';
async function maybeRead(path){try{return await readFile(path);}catch(error){if(missing(error))return null;throw error;}}
const indexSource=index=>'// Append-only index generated by scripts/seal-research-release.mjs.\n// The index is deliberately excluded from the application source identity.\nexport const researchReleases='+JSON.stringify(Object.fromEntries(Object.entries(index).sort(([a],[b])=>a.localeCompare(b))))+';\n';
function parseIndex(source){
  const match=/\bexport const researchReleases=(\{[\s\S]*\});\s*$/.exec(source.toString('utf8'));
  if(!match)throw Error('RESEARCH_RELEASE_INDEX_FORMAT');
  const index=JSON.parse(match[1]);if(!index||typeof index!=='object'||Array.isArray(index)||Object.keys(index).some(build=>!/^[a-f0-9]{64}$/.test(build)))throw Error('RESEARCH_RELEASE_INDEX_FORMAT');
  return index;
}
async function readIndex(path){const source=await maybeRead(path);return source?parseIndex(source):{};}

/** The append-only index and pack bytes stay authoritative. The Worker needs
 * only route identities to find a pack; its checksum protects full metadata. */
function runtimeEntries(index){
  return Object.fromEntries(Object.entries(index).map(([build,entry])=>{
    if(typeof entry?.rowsGzip!=='string'||entry.rowsFormat!==undefined&&![RESEARCH_RELEASE_FULL_ROWS,RESEARCH_RELEASE_ROW_IDENTITIES].includes(entry.rowsFormat))throw Error('RESEARCH_RELEASE_INDEX_FORMAT');
    const rows=JSON.parse(gunzipSync(Buffer.from(entry.rowsGzip,'base64'),{maxOutputLength:8*1024*1024}).toString('utf8'));
    const identities=researchReleaseRowIdentities(rows);
    if(entry.rowsFormat===RESEARCH_RELEASE_ROW_IDENTITIES&&JSON.stringify(identities)!==JSON.stringify(rows))throw Error('RESEARCH_RELEASE_ROW_IDENTITY_FORMAT');
    return [build,{...entry,rowsGzip:gzip(JSON.stringify(identities)).toString('base64'),rowsFormat:RESEARCH_RELEASE_ROW_IDENTITIES}];
  }));
}
export function researchReleaseRuntimeIndexSource(index){
  const rows=[],slots=new Map(),compact={};
  for(const [build,entry]of Object.entries(runtimeEntries(index))){
    if(!slots.has(entry.rowsGzip)){slots.set(entry.rowsGzip,rows.length);rows.push(entry.rowsGzip);}
    compact[build]={...entry,rowsGzip:slots.get(entry.rowsGzip)};
  }
  return '// Generated by scripts/seal-research-release.mjs from the append-only research index.\n// Route identity projection only; full metadata remains in checksummed immutable packs.\nconst rows='+JSON.stringify(rows)+';\nexport const researchReleases=Object.fromEntries(Object.entries('+JSON.stringify(compact)+').map(([build,entry])=>[build,{...entry,rowsGzip:rows[entry.rowsGzip]}]));\n';
}

export async function syncResearchReleaseRuntimeIndex({indexPath=join(repository,'src/server/research-app/releases.gen.mjs'),runtimeIndexPath=join(repository,'src/server/research-release-runtime-index.gen.mjs'),check=false}={}){
  const update=async()=>{
    const before=await maybeRead(indexPath);if(!before)throw Error('RESEARCH_RELEASE_INDEX_MISSING');
    const index=parseIndex(before),output=researchReleaseRuntimeIndexSource(index),previous=await maybeRead(runtimeIndexPath);
    const changed=previous?.toString('utf8')!==output;
    if(check&&changed)throw Error('RESEARCH_RELEASE_RUNTIME_INDEX_STALE');
    if(!check&&changed){
      await mkdir(dirname(runtimeIndexPath),{recursive:true});
      const temporary=runtimeIndexPath+'.tmp-'+process.pid;
      try{
        await writeFile(temporary,output,{flag:'wx'});
        if(!(await readFile(indexPath)).equals(before))throw Error('RESEARCH_RELEASE_INDEX_CHANGED');
        await rename(temporary,runtimeIndexPath);
      }finally{try{await unlink(temporary);}catch(error){if(!missing(error))throw error;}}
    }
    return {releases:Object.keys(index).length,uniqueRows:new Set(Object.values(runtimeEntries(index)).map(entry=>entry.rowsGzip)).size,bytes:Buffer.byteLength(output),changed,checked:check};
  };
  if(check)return update();
  // Share the sealer's lock so concurrent release writers cannot leave a stale
  // runtime index. A later sealer regenerates from the complete current index.
  const lock=indexPath+'.lock';
  try{await writeFile(lock,String(process.pid)+'\n',{flag:'wx'});}catch(error){if(error.code==='EEXIST')throw Error('RESEARCH_RELEASE_INDEX_BUSY');throw error;}
  try{return await update();}finally{await unlink(lock);}
}

/** Collect the actual served bytes, including current regular extensions. */
export async function collectResearchRelease(page){
  if(!page?.listResearchRows||!page.listResearchAssetPaths||!page.serveResearchAsset||!page.renderResearchApplication)throw Error('RESEARCH_RELEASE_COLLECTOR_CONTRACT');
  const build=page.researchBuild;if(build?.format!=='order-research-build/v1'||hash(JSON.stringify(build.sources))!==build.digest)throw Error('RESEARCH_RELEASE_BUILD_IDENTITY');
  const rows=await page.listResearchRows(),paths=[...new Set(await page.listResearchAssetPaths())].sort(),assets={};
  if(!paths.length||paths.some(path=>!safePath(path)))throw Error('RESEARCH_RELEASE_ASSET_PATHS');
  const base='/ia/research-assets/'+build.digest+'/';
  for(const path of paths){
    const response=await page.serveResearchAsset(base+path);
    if(response.status!==200)throw Error('RESEARCH_RELEASE_ASSET_MISSING: '+path);
    const type=response.headers.get('Content-Type')||'text/javascript; charset=utf-8';
    assets[path]={body:await response.text(),type};
  }
  // These checks catch a missing relative dependency in the release inventory.
  // Runtime-computed imports are represented by listResearchAssetPaths itself.
  for(const [path,asset]of Object.entries(assets))if(/javascript/.test(asset.type)){
    const references=[...asset.body.matchAll(/(?:^|\n)\s*(?:import|export)\s+(?:[^;\n]*?\s+from\s*)?['"]([^'"]+)['"]/g),...asset.body.matchAll(/\bimport\(\s*['"]([^'"]+)['"]\s*\)/g)].map(match=>match[1]);
    for(const reference of references){
      const dependency=reference.startsWith('./')||reference.startsWith('../')?posix.normalize(posix.join(posix.dirname(path),reference)):reference.startsWith(base)?reference.slice(base.length):null;
      if(dependency&&!Object.hasOwn(assets,dependency))throw Error('RESEARCH_RELEASE_DEPENDENCY_MISSING: '+path+' -> '+dependency);
      if(reference.startsWith('/ia/research-assets/')&&!reference.startsWith(base))throw Error('RESEARCH_RELEASE_CROSS_BUILD_IMPORT: '+path);
    }
  }
  const html=await page.renderResearchApplication(RESEARCH_RELEASE_NONCE,new URLSearchParams({screen:'onboarding',state:'guest-1'}));
  return {format:RESEARCH_RELEASE_FORMAT,build,rows,shell:{html,nonce:RESEARCH_RELEASE_NONCE},assets};
}

export function encodeResearchRelease(pack,{rowsFormat=RESEARCH_RELEASE_ROW_IDENTITIES}={}){
  // null reproduces the original untagged full-row entry for immutable archives.
  // It is used only when checking an existing entry; newly sealed builds use the
  // explicit compact format and never duplicate catalog hashes in the Worker.
  if(rowsFormat!==null&&![RESEARCH_RELEASE_FULL_ROWS,RESEARCH_RELEASE_ROW_IDENTITIES].includes(rowsFormat))throw Error('RESEARCH_RELEASE_ROWS_FORMAT');
  const rows=rowsFormat===RESEARCH_RELEASE_ROW_IDENTITIES?researchReleaseRowIdentities(pack.rows):pack.rows;
  const raw=Buffer.from(JSON.stringify(pack)),bytes=gzip(raw),entry={packSha256:hash(bytes),bytes:bytes.byteLength,...(rowsFormat===null?{}:{rowsFormat}),rowsGzip:gzip(Buffer.from(JSON.stringify(rows))).toString('base64')};
  return {bytes,entry,rawBytes:raw.byteLength};
}

/** Checks all prior packs against the trusted append-only index. */
export async function verifyResearchReleaseFiles(index,directory){
  for(const [build,entry]of Object.entries(index)){
    if(!/^[a-f0-9]{64}$/.test(build))throw Error('RESEARCH_RELEASE_INDEX_FORMAT');
    const file=join(directory,build+'.json.gz'),bytes=await maybeRead(file);
    if(!bytes)throw Error('RESEARCH_RELEASE_MISSING_PACK: '+build);
    if(bytes.byteLength!==entry.bytes||hash(bytes)!==entry.packSha256)throw Error('RESEARCH_RELEASE_ARCHIVE_CHANGED: '+build);
    const store=createResearchReleaseStore({[build]:entry});
    await store.read(build,{ASSETS:{fetch:async request=>{
      if(new URL(request.url).pathname!=='/ia/research-releases/'+build+'.json.gz')throw Error('RESEARCH_RELEASE_PATH');
      return new Response(bytes,{headers:{'Content-Type':'application/gzip'}});
    }}},'https://release-check.invalid');
  }
}

/** A new build is written once; a known digest can never replace its bytes. */
async function sealUnlocked(pack,{directory=join(repository,'public/ia/research-releases'),indexPath=join(repository,'src/server/research-app/releases.gen.mjs'),check=false}={}){
  const build=pack.build?.digest;if(!/^[a-f0-9]{64}$/.test(build||''))throw Error('RESEARCH_RELEASE_BUILD_IDENTITY');
  const index=await readIndex(indexPath),existing=index[build],file=join(directory,build+'.json.gz');
  const {bytes,entry,rawBytes}=encodeResearchRelease(pack,existing?{rowsFormat:Object.hasOwn(existing,'rowsFormat')?existing.rowsFormat:null}:{});
  const previous=await maybeRead(file);
  if(previous&&!previous.equals(bytes))throw Error('RESEARCH_RELEASE_IMMUTABLE_COLLISION: '+build);
  if(existing&&JSON.stringify(existing)!==JSON.stringify(entry))throw Error('RESEARCH_RELEASE_INDEX_COLLISION: '+build);
  if(existing&&!previous)throw Error('RESEARCH_RELEASE_MISSING_PACK: '+build);
  const expected={...index,[build]:entry};
  // Validate the freshly collected pack before writing either durable artifact.
  await createResearchReleaseStore({[build]:entry}).read(build,{ASSETS:{fetch:async()=>new Response(bytes)}},'https://seal-check.invalid');
  if(check){
    if(!existing||!previous)throw Error('RESEARCH_RELEASE_NOT_SEALED: '+build);
    await verifyResearchReleaseFiles(index,directory);
    return {build,bytes:bytes.byteLength,rawBytes,assets:Object.keys(pack.assets).length,rows:pack.rows.length,releases:Object.keys(index).length,checked:true};
  }
  await verifyResearchReleaseFiles(index,directory);
  if(!previous){await mkdir(directory,{recursive:true});await writeFile(file,bytes,{flag:'wx'});}
  if(!existing){
    await mkdir(dirname(indexPath),{recursive:true});
    // Re-read immediately before the atomic index rename. Concurrent writers
    // must not silently remove an entry another sealing process just added.
    if(JSON.stringify(await readIndex(indexPath))!==JSON.stringify(index))throw Error('RESEARCH_RELEASE_INDEX_CHANGED');
    const temporary=indexPath+'.tmp-'+process.pid;
    await writeFile(temporary,indexSource(expected),{flag:'wx'});await rename(temporary,indexPath);
  }
  return {build,bytes:bytes.byteLength,rawBytes,assets:Object.keys(pack.assets).length,rows:pack.rows.length,releases:Object.keys(expected).length,sealed:!existing};
}

export async function sealResearchRelease(pack,options={}){
  if(options.check)return sealUnlocked(pack,options);
  const indexPath=options.indexPath||join(repository,'src/server/research-app/releases.gen.mjs'),lock=indexPath+'.lock';
  await mkdir(dirname(indexPath),{recursive:true});
  try{await writeFile(lock,String(process.pid)+'\n',{flag:'wx'});}catch(error){if(error.code==='EEXIST')throw Error('RESEARCH_RELEASE_INDEX_BUSY');throw error;}
  try{return await sealUnlocked(pack,{...options,indexPath});}finally{await unlink(lock);}
}

export async function main(args=process.argv.slice(2)){
  if(args.some(arg=>!['--check','--help'].includes(arg)))throw Error('Usage: node scripts/seal-research-release.mjs [--check]');
  if(args.includes('--help')){console.log('Seal the current research build once, or verify its immutable pack and all earlier packs with --check.');return;}
  // Read-only gate: never refresh source identities as a side effect of sealing.
  execFileSync(process.execPath,['scripts/build-research-app.mjs','--check'],{cwd:repository,encoding:'utf8',maxBuffer:1024*1024});
  const page=await import(pathToFileURL(join(repository,'src/server/research-app/page.mjs')).href);
  const check=args.includes('--check'),pack=await collectResearchRelease(page),result=await sealResearchRelease(pack,{check});
  const runtimeIndex=await syncResearchReleaseRuntimeIndex({check});console.log(JSON.stringify({...result,runtimeIndex}));
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url))await main();
