import {createHash} from 'node:crypto';
import {mkdir,readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {serveR3Artifact} from '../src/server/r3-qa-page.mjs';
import {publicationIdentity} from '../src/server/r3-qa-publication.mjs';
import {researchBuild} from '../src/server/research-app/assets.gen.mjs';

const directory=new URL('../public/ia/research-releases/qa-catalog/',import.meta.url);
const manifest=new URL('../src/server/r3-qa-catalog-identity.gen.mjs',import.meta.url);
const check=process.argv.includes('--check');
async function save(file,bytes){
  if(!check){await writeFile(file,bytes);return;}
  if(!(await readFile(file)).equals(bytes))throw Error('Generated QA catalog mismatch: '+fileURLToPath(file));
}
if(!check)await mkdir(directory,{recursive:true});
const modes={};
for(const mode of ['simple','detailed']){
  const response=await serveR3Artifact(new Request('https://qa.invalid/api/ia/r3-qa/artifact?mode='+mode));
  if(!response.ok)throw Error('QA catalog unavailable: '+mode);
  const bytes=Buffer.from(await response.arrayBuffer()),sha256=createHash('sha256').update(bytes).digest('hex');
  // Keep catalog bytes intact. Only the hostname-specific D1 receipt is filled by the request.
  const suffix=Buffer.from('"publication":null'+(mode==='detailed'?',"mode":"detailed"':'')+'}');
  if(!bytes.subarray(-suffix.length).equals(suffix))throw Error('QA catalog publication field moved: '+mode);
  modes[mode]={sha256,bytes:bytes.length,publicationOffset:bytes.length-suffix.length+Buffer.byteLength('"publication":')};
  await save(new URL(sha256+'.json',directory),bytes);
}
const identity={build:researchBuild.digest,publication:await publicationIdentity(),modes};
await save(manifest,Buffer.from('// Generated by scripts/build-qa-research-catalog.mjs.\nexport const qaCatalogIdentity='+JSON.stringify(identity)+';\n'));
console.log(JSON.stringify({build:identity.build,modes,checked:check}));
